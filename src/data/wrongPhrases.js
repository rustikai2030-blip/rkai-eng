// Загрузка фраз (с поддержкой localStorage для редактирования из админки)
export function getWrongPhrases() {
  const saved = localStorage.getItem('rkai_wrong_phrases');
  if (saved) {
    try {
      return JSON.parse(saved);
    } catch (e) {
      console.error("Ошибка парсинга фраз из localStorage", e);
    }
  }
  return initialWrongPhrases;
}

export function saveWrongPhrases(phrasesObj) {
  localStorage.setItem('rkai_wrong_phrases', JSON.stringify(phrasesObj));
}